// JAVASCRIPT

let n1 = Number(window.prompt("Digite um número: "));
let n2 = Number(window.prompt("Digite outro número: "));

// SOMA

const soma = n1 + n2;

window.alert(`A soma dos valores é ${soma}`);

// DEMAIS OPERADORES

// MULTIPLICAÇÃO

let mult = n1 * n2;
document.writeln(`<br>A multiplicação de ${n1} e ${n2} é igual a ${mult}.`);

// SUBTRAÇÃO

let sub = n1 - n2;
document.writeln(`<br>A subtração de ${n1} e ${n2} é igual a ${sub}.`);

// POTÊNCIA

let pot = n1 ** n2;
document.writeln(`<br>A potência de ${n1} e ${n2} é igual a ${pot}.`);

// DIVISÃO REAL

let divr = n1 / n2;
document.writeln(`<br>A divisão real de ${n1} e ${n2} é igual a ${divr}.`);

// RESTO DA DIVISÃO

let rdiv = n1 % n2;
document.writeln(`<br>O resto da divisão de ${n1} e ${n2} é igual a ${rdiv}.`);

// OPERADOR DE ATRIBUIÇÃO

n1 += n2;
document.writeln(`<br><br> ${n1}`);
n1 += n2;
document.writeln(`<br><br> ${n1}`);
n1 += n2;
document.writeln(`<br><br> ${n1}`);
